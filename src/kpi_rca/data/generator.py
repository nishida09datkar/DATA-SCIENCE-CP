"""Synthetic checkout event stream with injected incidents and support tickets.

One row per checkout attempt. Traffic follows a daily and weekly profile with a small
per-day random factor; dimension mixes are country-specific (PayPal is popular in DE,
Android dominates IN/BR, desktop rows are "web"). Baseline success comes from a
logistic model with per-dimension effects, so some segments (e.g. BR) convert worse
all the time - that is normal, not an incident.

Injected incidents force failures with a dedicated error code inside one segment for a
limited time and make some affected customers write support tickets shortly after.
Benign events (marketing surges) add traffic without changing conversion. Background
tickets cover unrelated topics plus deliberate decoys (card declines elsewhere, PayPal
refunds, app slowness, login timeouts) so that retrieval has to be selective.

Ticket metadata uses the checkout row values (ISO-2 country, iOS/Android/Windows/macOS);
missing values are None, never placeholder strings.
"""

