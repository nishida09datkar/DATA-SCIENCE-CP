# ------------------------------------------------------------------ ground truth


class IncidentTruth(BaseModel):
    incident_id: str
    segment: dict[str, str]
    start: datetime
    end: datetime  # exclusive
    failure_rate: float
    error_code: str
    segment_attempts: int  # attempts in the segment during the incident
    forced_failures: int  # attempts that failed because of the incident
    tickets: int  # support tickets generated by the incident
    segment_share: float  # share of all attempts during the incident that fall in the segment


class BenignTruth(BaseModel):
    event_id: str
    kind: str
    segment: dict[str, str]
    start: datetime
    end: datetime  # exclusive
    volume_multiplier: float
    description: str = ""
    extra_attempts: int = 0


class GroundTruth(BaseModel):
    seed: int
    start: datetime
    end: datetime  # exclusive
    incidents: list[IncidentTruth]
    benign_events: list[BenignTruth]


@dataclass
class Scenario:
    transactions: pd.DataFrame
    tickets: pd.DataFrame
    ground_truth: GroundTruth | None = None  # None for data that was not generated here


