def _device_phrase(os_name: str | None, device: str | None, rng: np.random.Generator) -> str:
    options = _DEVICE_PHRASES.get((os_name or "", device or ""))
    if not options:
        return "phone"
    return str(options[rng.integers(len(options))])


def _app_phrase(os_name: str | None, device: str | None, rng: np.random.Generator) -> str:
    if device == "desktop":
        return str(rng.choice(["the website", "the browser checkout", "the web shop"]))
    if os_name == "iOS":
        return str(rng.choice(["the iPhone app", "the iOS app", "the app"]))
    if os_name == "Android":
        return str(rng.choice(["the Android app", "the app"]))
    return "the app"


def _render(
    core_bank: list[str],
    rng: np.random.Generator,
    *,
    os_name: str | None = None,
    device: str | None = None,
    gateway: str | None = None,
    version: str | None = None,
) -> str:
    core = core_bank[rng.integers(len(core_bank))]
    methods = _METHOD_PHRASES.get(gateway or "", ["card"])
    slots = {
        "device": _device_phrase(os_name, device, rng),
        "app": _app_phrase(os_name, device, rng),
        "method": str(methods[rng.integers(len(methods))]),
        "version": version if version and version != WEB_APP_VERSION else "the latest version",
        "order": str(int(rng.integers(100000, 999999))),
    }
    text = core.format(**slots)
    opener = _OPENERS[rng.integers(len(_OPENERS))]
    closer = _CLOSERS[rng.integers(len(_CLOSERS))].format(**slots)
    return " ".join(part for part in (opener, text, closer) if part)


# ------------------------------------------------------------------ sampling


def _normalise(weights: dict[str, float], order: list[str]) -> np.ndarray:
    p = np.array([float(weights.get(k, 0.0)) for k in order], dtype=float)
    if p.sum() <= 0:
        raise ValueError(f"weights {weights} give zero mass over {order}")
    return p / p.sum()


def _choice_by_group(
    rng: np.random.Generator, group_idx: np.ndarray, n_groups: int, probs: list[np.ndarray]
) -> np.ndarray:
    """Draw one category per row with group-specific probabilities (vectorised per group)."""
    out = np.empty(group_idx.shape[0], dtype=np.int64)
    for g in range(n_groups):
        rows = np.flatnonzero(group_idx == g)
        if rows.size:
            out[rows] = rng.choice(probs[g].shape[0], size=rows.size, p=probs[g])
    return out


class _Dims:
    """Category orders and conditional distributions derived from the config."""

    def __init__(self, cfg: DataConfig) -> None:
        self.countries = list(cfg.countries)
        self.os = list(cfg.os)
        self.devices = list(DEVICE_TYPES)
        self.gateways = list(cfg.payment_gateways)
        self.mobile_versions = list(cfg.app_versions)
        self.versions = [*self.mobile_versions, WEB_APP_VERSION]
        self.country_p = _normalise(cfg.countries, self.countries)
        self.os_p = [_normalise(cfg.country_os.get(c, cfg.os), self.os) for c in self.countries]
        self.device_p = [_normalise(cfg.device_given_os[o], self.devices) for o in self.os]
        self.gateway_p = [_normalise(cfg.country_gateways.get(c, cfg.payment_gateways), self.gateways) for c in self.countries]
        self.version_p = _normalise(cfg.app_versions, self.mobile_versions)
        self.categories = {
            "country": self.countries,
            "os": self.os,
            "device_type": self.devices,
            "payment_gateway": self.gateways,
            "app_version": self.versions,
        }

    def code(self, attribute: str, value: str) -> int:
        cats = self.categories[attribute]
        return cats.index(value) if value in cats else -1


def _sample_attributes(
    dims: _Dims, rng: np.random.Generator, country_idx: np.ndarray
) -> dict[str, np.ndarray]:
    n_c = len(dims.countries)
    os_idx = _choice_by_group(rng, country_idx, n_c, dims.os_p)
    device_idx = _choice_by_group(rng, os_idx, len(dims.os), dims.device_p)
    gateway_idx = _choice_by_group(rng, country_idx, n_c, dims.gateway_p)
    version_idx = np.full(country_idx.shape[0], len(dims.versions) - 1, dtype=np.int64)  # "web"
    is_app = device_idx != dims.devices.index("desktop")
    version_idx[is_app] = rng.choice(len(dims.mobile_versions), size=int(is_app.sum()), p=dims.version_p)
    return {
        "country": country_idx,
        "os": os_idx,
        "device_type": device_idx,
        "payment_gateway": gateway_idx,
        "app_version": version_idx,
    }


def _segment_mask(dims: _Dims, codes: dict[str, np.ndarray], segment: dict[str, str]) -> np.ndarray:
    n = next(iter(codes.values())).shape[0]
    mask = np.ones(n, dtype=bool)
    for attr, value in segment.items():
        mask &= codes[attr] == dims.code(attr, value)
    return mask


def _traffic_profile(cfg: DataConfig, hours: pd.DatetimeIndex, rng: np.random.Generator) -> np.ndarray:
    """Expected attempts per hour: mean level x hour-of-day shape x day-level factor.

    The day-level factor (weekday profile x lognormal day noise) is set at each day's
    midpoint and joined by a natural cubic spline on the log scale, so traffic drifts
    smoothly from one day to the next instead of jumping at midnight or bending sharply
    at noon (real traffic has neither).
    """
    hourly = np.asarray(cfg.hourly_profile, dtype=float)
    hourly = hourly / hourly.mean()
    weekly = np.asarray(cfg.weekly_profile, dtype=float)
    weekly = weekly / weekly.mean()
    sigma = cfg.daily_traffic_noise
    n_days = cfg.days + 1
    day_noise = rng.normal(-0.5 * sigma**2, sigma, size=n_days)
    day_starts = pd.date_range(hours[0].normalize(), periods=n_days, freq="D")
    log_day = np.log(weekly[np.asarray(day_starts.dayofweek)]) + day_noise
    midpoints_h = np.arange(n_days) * 24.0 + 11.5
    hour_offset = np.asarray((hours - day_starts[0]) / pd.Timedelta(hours=1), dtype=float)
    day_factor = np.exp(CubicSpline(midpoints_h, log_day, bc_type="natural")(hour_offset))
    return cfg.attempts_per_hour * hourly[np.asarray(hours.hour)] * day_factor


def _effect_array(effects: dict[str, float], categories: list[str]) -> np.ndarray:
    return np.array([float(effects.get(v, 0.0)) for v in categories], dtype=float)


# ------------------------------------------------------------------- generator


def generate_scenario(data_cfg: DataConfig, seed: int) -> Scenario:
    """Generate transactions, tickets and the ground truth for one scenario (deterministic per seed)."""
    rng = np.random.default_rng(seed)
    dims = _Dims(data_cfg)
    hours = pd.date_range(data_cfg.start, periods=data_cfg.days * 24, freq="h")
    n_hours = len(hours)
    hour_ns = hours.values.astype("datetime64[ns]").astype(np.int64)

    # ---- attempts: base traffic per (hour, country) plus benign surges ----
    lam = _traffic_profile(data_cfg, hours, rng)[:, None] * dims.country_p[None, :]
    counts = rng.poisson(lam)
    flat = np.repeat(np.arange(counts.size), counts.ravel())
    hour_idx = flat // len(dims.countries)
    codes = _sample_attributes(dims, rng, flat % len(dims.countries))

    benign_truth: list[BenignTruth] = []
    for event in data_cfg.benign_events:
        in_event = (hours >= event.start) & (hours < event.end)
        extra_lam = np.zeros_like(lam)
        country = event.segment.get("country")
        cols = [dims.code("country", country)] if country else list(range(len(dims.countries)))
        for c in cols:
            extra_lam[in_event, c] = (event.volume_multiplier - 1.0) * lam[in_event, c]
        extra_lam = np.clip(extra_lam, 0.0, None)
        extra_counts = rng.poisson(extra_lam)
        extra_flat = np.repeat(np.arange(extra_counts.size), extra_counts.ravel())
        extra_codes = _sample_attributes(dims, rng, extra_flat % len(dims.countries))
        # Candidates come from the country's own mix; keep those matching the rest of the
        # segment so the segment's rate is multiplied while its internal mix is unchanged.
        keep = _segment_mask(dims, extra_codes, event.segment)
        hour_idx = np.concatenate([hour_idx, (extra_flat // len(dims.countries))[keep]])
        for attr in codes:
            codes[attr] = np.concatenate([codes[attr], extra_codes[attr][keep]])
        benign_truth.append(
            BenignTruth(
                event_id=event.event_id,
                kind=event.kind,
                segment=dict(event.segment),
                start=event.start,
                end=event.end,
                volume_multiplier=event.volume_multiplier,
                description=event.description,
                extra_attempts=int(keep.sum()),
            )
        )

    n = hour_idx.shape[0]
    ts = hour_ns[hour_idx] + (rng.random(n) * _NS_PER_HOUR).astype(np.int64)
    order = np.argsort(ts, kind="stable")
    ts = ts[order]
    hour_idx = hour_idx[order]
    codes = {attr: arr[order] for attr, arr in codes.items()}

    # ---- baseline success from a logistic model with per-dimension effects ----
    base = data_cfg.base_conversion
    logit = np.full(n, np.log(base / (1.0 - base)))
    for attr, effects in data_cfg.conversion_effects.items():
        logit += _effect_array(effects, dims.categories[attr])[codes[attr]]
    hour_of_day = np.asarray(hours.hour)[hour_idx]
    logit += data_cfg.hourly_conversion_amplitude * np.cos(2 * np.pi * (hour_of_day - 15) / 24.0)
    p_success = 1.0 / (1.0 + np.exp(-logit))
    success = (rng.random(n) < p_success).astype(np.int64)

    baseline_codes = list(data_cfg.error_mix)
    incident_codes = [inc.error_code for inc in data_cfg.incidents if inc.error_code not in baseline_codes]
    error_categories = ["NONE", *baseline_codes, *dict.fromkeys(incident_codes)]
    error_idx = np.zeros(n, dtype=np.int64)
    failed = success == 0
    error_idx[failed] = 1 + rng.choice(
        len(baseline_codes), size=int(failed.sum()), p=_normalise(data_cfg.error_mix, baseline_codes)
    )

    country_scale = _effect_array(data_cfg.country_amount_scale, dims.countries)
    country_scale[country_scale <= 0] = 1.0
    amount = np.exp(rng.normal(data_cfg.amount_log_mean, data_cfg.amount_log_sigma, size=n))
    amount = np.round(np.maximum(amount * country_scale[codes["country"]], 1.0), 2)

    gw_scale = _effect_array(data_cfg.gateway_latency_scale, dims.gateways)
    gw_scale[gw_scale <= 0] = 1.0
    latency = data_cfg.latency_median_ms * gw_scale[codes["payment_gateway"]]
    latency = latency * np.exp(rng.normal(0.0, data_cfg.latency_log_sigma, size=n))

    # ---- incidents: forced failures inside the segment and time range ----
    incident_rows: list[tuple[IncidentSpec, np.ndarray]] = []
    incident_truth_parts = []
    for inc in data_cfg.incidents:
        start_ns = np.datetime64(inc.start, "ns").astype(np.int64)
        end_ns = np.datetime64(inc.end, "ns").astype(np.int64)
        in_time = (ts >= start_ns) & (ts < end_ns)
        in_seg = in_time & _segment_mask(dims, codes, inc.segment)
        forced = in_seg & (rng.random(n) < inc.failure_rate)
        success[forced] = 0
        error_idx[forced] = error_categories.index(inc.error_code)
        latency[forced] *= inc.latency_multiplier
        incident_rows.append((inc, np.flatnonzero(forced)))
        incident_truth_parts.append((int(in_seg.sum()), int(forced.sum()), float(in_seg.sum() / max(in_time.sum(), 1))))

    transactions = pd.DataFrame(
        {
            "transaction_id": pd.array(np.char.mod("TX%09d", np.arange(n)), dtype="str"),
            "timestamp": pd.to_datetime(ts.astype("datetime64[ns]")),
            **{
                attr: pd.Categorical.from_codes(codes[attr], categories=dims.categories[attr])
                for attr in ("country", "os", "device_type", "payment_gateway", "app_version")
            },
            "amount": amount.astype(float),
            "success": success,
            "error_code": pd.Categorical.from_codes(error_idx, categories=error_categories),
            "latency_ms": np.round(latency, 1).astype(float),
        }
    )

    # ---- tickets ----
    tickets, ticket_counts = _generate_tickets(data_cfg, dims, rng, hours, transactions, incident_rows)

    truth = GroundTruth(
        seed=seed,
        start=data_cfg.start,
        end=data_cfg.end,
        incidents=[
            IncidentTruth(
                incident_id=inc.incident_id,
                segment=dict(inc.segment),
                start=inc.start,
                end=inc.end,
                failure_rate=inc.failure_rate,
                error_code=inc.error_code,
                segment_attempts=part[0],
                forced_failures=part[1],
                tickets=ticket_counts.get(inc.incident_id, 0),
                segment_share=part[2],
            )
            for (inc, _), part in zip(incident_rows, incident_truth_parts)
        ],
        benign_events=benign_truth,
    )
    log.info(
        "generated %d attempts, %d tickets, %d incidents, %d benign events",
        len(transactions),
        len(tickets),
        len(truth.incidents),
        len(truth.benign_events),
    )
    return Scenario(transactions=transactions, tickets=tickets, ground_truth=truth)


def _generate_tickets(
    cfg: DataConfig,
    dims: _Dims,
    rng: np.random.Generator,
    hours: pd.DatetimeIndex,
    tx: pd.DataFrame,
    incident_rows: list[tuple[IncidentSpec, np.ndarray]],
) -> tuple[pd.DataFrame, dict[str, int]]:
    tcfg = cfg.tickets
    channels = list(tcfg.channel_weights)
    channel_p = _normalise(tcfg.channel_weights, channels)
    records: list[dict] = []

    # Background tickets follow the traffic profile (no day noise, no surges).
    hourly = np.asarray(cfg.hourly_profile, dtype=float)
    hourly = hourly / hourly.mean()
    weekly = np.asarray(cfg.weekly_profile, dtype=float)
    weekly = weekly / weekly.mean()
    lam = tcfg.background_per_hour * hourly[np.asarray(hours.hour)] * weekly[np.asarray(hours.dayofweek)]
    per_hour = rng.poisson(lam)
    themes = list(tcfg.theme_weights)
    theme_p = _normalise(tcfg.theme_weights, themes)
    # Decline complaints come from where declines happen: weight countries by baseline failure.
    base = cfg.base_conversion
    country_eff = _effect_array(cfg.conversion_effects.get("country", {}), dims.countries)
    country_fail = 1.0 - 1.0 / (1.0 + np.exp(-(np.log(base / (1 - base)) + country_eff)))
    decline_country_p = dims.country_p * country_fail / (dims.country_p * country_fail).sum()

    hour_starts = hours.values.astype("datetime64[ns]").astype(np.int64)
    for h in np.flatnonzero(per_hour):
        for _ in range(per_hour[h]):
            theme = themes[rng.choice(len(themes), p=theme_p)]
            cp = decline_country_p if theme == "generic_decline" else dims.country_p
            c = int(rng.choice(len(dims.countries), p=cp))
            o = int(rng.choice(len(dims.os), p=dims.os_p[c]))
            d = int(rng.choice(len(dims.devices), p=dims.device_p[o]))
            g = int(rng.choice(len(dims.gateways), p=dims.gateway_p[c]))
            text = _render(
                _BACKGROUND_CORE[theme], rng, os_name=dims.os[o], device=dims.devices[d], gateway=dims.gateways[g]
            )
            created = hour_starts[h] + int(rng.random() * _NS_PER_HOUR)
            records.append(_ticket_record(rng, tcfg, channels, channel_p, created, dims.countries[c], dims.os[o], text, None))

    # Incident tickets: a fraction of the forced failures write in shortly afterwards.
    end_ns = np.datetime64(cfg.end, "ns").astype(np.int64)
    ts_ns = tx["timestamp"].values.astype("datetime64[ns]").astype(np.int64)
    counts: dict[str, int] = {}
    for inc, rows in incident_rows:
        writers = rows[rng.random(rows.size) < inc.ticket_rate]
        n_written = 0
        for r in writers:
            delay_min = min(rng.exponential(tcfg.delay_mean_minutes), tcfg.delay_max_hours * 60.0)
            created = ts_ns[r] + int(delay_min * 60e9)
            if created >= end_ns:
                continue
            row = tx.iloc[r]
            theme = inc.ticket_themes[rng.integers(len(inc.ticket_themes))]
            text = _render(
                _INCIDENT_CORE[theme],
                rng,
                os_name=str(row["os"]),
                device=str(row["device_type"]),
                gateway=str(row["payment_gateway"]),
                version=str(row["app_version"]),
            )
            records.append(
                _ticket_record(
                    rng, tcfg, channels, channel_p, created, str(row["country"]), str(row["os"]), text, inc.incident_id
                )
            )
            n_written += 1
        counts[inc.incident_id] = n_written

    tickets = pd.DataFrame.from_records(records, columns=["created_ns", *TICKET_COLUMNS[2:]])
    tickets = tickets.sort_values("created_ns", kind="stable").reset_index(drop=True)
    created_at = pd.to_datetime(tickets["created_ns"].to_numpy(dtype=np.int64).astype("datetime64[ns]"))
    out = pd.DataFrame(
        {
            "ticket_id": pd.array([f"TK{i:06d}" for i in range(len(tickets))], dtype="str"),
            "created_at": created_at,
            "channel": pd.array(tickets["channel"].tolist(), dtype="str"),
            "customer_country": pd.array(tickets["customer_country"].tolist(), dtype="str"),
            "device_os": pd.array(tickets["device_os"].tolist(), dtype="str"),
            "text": pd.array(tickets["text"].tolist(), dtype="str"),
            "gt_incident_id": pd.array(tickets["gt_incident_id"].tolist(), dtype="str"),
        }
    )
    return out, counts


def _ticket_record(
    rng: np.random.Generator,
    tcfg,
    channels: list[str],
    channel_p: np.ndarray,
    created_ns: int,
    country: str,
    os_name: str,
    text: str,
    incident_id: str | None,
) -> dict:
    return {
        "created_ns": int(created_ns),
        "channel": channels[rng.choice(len(channels), p=channel_p)],
        "customer_country": None if rng.random() < tcfg.null_country_prob else country,
        "device_os": None if rng.random() < tcfg.null_os_prob else os_name,
        "text": text,
        "gt_incident_id": incident_id,
    }
